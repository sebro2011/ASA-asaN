def month_block(table: dict[int, tuple[list[float], float]]) -> dict[str, float]:
    block: dict[str, float] = {}
    for year, (months, annual) in sorted(table.items()):
        for index, value in enumerate(months, start=1):
            block[f"{year}{index:02d}"] = value
        block[f"{year}13"] = annual
    return block


def verify_annual_consistency(name: str, param: str,
                              table: dict[int, tuple[list[float], float]],
                              tolerance: float) -> tuple[int, float, list[str]]:
    """POWER's month 13 is the annual mean; a transcription slip breaks that link."""
    failures: list[str] = []
    worst = 0.0
    for year, (months, annual) in sorted(table.items()):
        monthly_mean = sum(months) / 12.0
        diff = abs(monthly_mean - annual)
        worst = max(worst, diff)
        if diff > tolerance:
            failures.append(f"{year}: mean={monthly_mean:.3f} annual={annual:.3f} diff={diff:.3f}")
    return len(table), worst, failures


TOLERANCES = {"T2M": 0.08, "PRECTOTCORR": 0.20}
PARAMS = ("T2M", "PRECTOTCORR")


def build(cache_dir: Path) -> None:
    cache_dir.mkdir(parents=True, exist_ok=True)
    for name, spec in LOCATIONS.items():
        # Verify first, then write: the emitted payload carries its own check, so the
        # committed file can be re-validated without trusting this script's stdout.
        checks = {}
        for param in PARAMS:
            years, worst, failures = verify_annual_consistency(
                name, param, spec[param], TOLERANCES[param]
            )
            if failures:
                raise SystemExit(
                    f"{name} {param}: {len(failures)} year(s) failed the month-13 check; "
                    "refusing to write a payload that does not verify"
                )
            checks[param] = {
                "years_checked": years,
                "worst_abs_month13_diff": round(worst, 4),
                "tolerance": TOLERANCES[param],
                "status": "passed",
            }

        path = cache_dir / f"power_{name}_2000_2024.json"
        # The retrieval stamp is preserved across rebuilds so the artefact hash is
        # reproducible; it is stamped once, when the payload is first written.
        stamp = None
        if path.exists():
            try:
                stamp = json.loads(path.read_text(encoding="utf-8")).get("_cosmora_retrieved_utc")
            except (ValueError, OSError):
                stamp = None
        stamp = stamp or datetime.now(timezone.utc).isoformat(timespec="seconds")

        payload = {
            "type": "Feature",
            "geometry": {"type": "Point", "coordinates": [spec["lon"], spec["lat"], spec["elevation"]]},
            "properties": {
                "parameter": {param: month_block(spec[param]) for param in PARAMS}
            },
            "header": {
                "title": "NASA/POWER Source Native Resolution Monthly and Annual",
                "api": {"version": "v2.10.0", "name": "POWER Monthly and Annual API"},
                "sources": ["MERRA2"],
                "fill_value": -999.0,
                "time_standard": "LST",
                "start": "20000101",
                "end": "20241231",
            },
            "parameters": LONG_NAMES,
            "_cosmora_retrieved_utc": stamp,
            "_cosmora_retrieval_channel": (
                "NASA POWER API response captured by the agent fetch tool and transcribed "
                "into this file; the build sandbox has no direct HTTPS egress to "
                "power.larc.nasa.gov (TLS handshake refused)."
            ),
            "_cosmora_retrieval_url": (
                "https://power.larc.nasa.gov/api/temporal/monthly/point"
                f"?parameters=T2M,PRECTOTCORR&community=RE&longitude={spec['lon']}"
                f"&latitude={spec['lat']}&start=2000&end=2024&format=JSON"
            ),
            "_cosmora_transcription_check": {
                "method": "POWER's 13th value per year is the annual mean; it must equal "
                "the mean of the twelve transcribed months",
                "month_13_dropped_before_modelling": True,
                "parameters": checks,
            },
        }
        path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {path} ({path.stat().st_size/1024:.1f} kB)")


