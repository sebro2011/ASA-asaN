/**
 * ArModelViewer Component
 * 
 * Complies with WebXR and Google Model-Viewer specifications:
 * 1. SSR-safe dynamic loading of `@google/model-viewer` inside useEffect.
 * 2. <model-viewer> attributes:
 *    - `ar`
 *    - `ar-modes="webxr scene-viewer quick-look"`
 *    - `camera-controls`
 *    - `camera-orbit` (memoized)
 *    - `poster` (memoized)
 *    - `exposure` (memoized)
 *    - `auto-rotate`
 *    - dynamic `src` prop for `.glb` models
 * 3. Elevated AR launch button with `slot="ar-button"` for camera projection.
 */
export function ArModelViewer({
  src,
  iosSrc,
  poster,
  cameraOrbit,
  alt = 'NASA 3D Space Model in Augmented Reality',
  ar = true,
  arModes = STATIC_CONFIG.arModes,
  cameraControls = true,
  autoRotate = true,
  className = '',
  lang = 'en',
  onModelSelect
}) {
  const [selectedModel, setSelectedModel] = useState(DEFAULT_AR_MODELS[0]);
  const [customSrc, setCustomSrc] = useState('');
  const [isCustomActive, setIsCustomActive] = useState(false);
  const [isScriptLoaded, setIsScriptLoaded] = useState(false);
  const [viewerLoadError, setViewerLoadError] = useState(false);
  const [isArSupported, setIsArSupported] = useState(false);
  const [hasModelError, setHasModelError] = useState(false);
  const [showQrModal, setShowQrModal] = useState(false);
  const [qrImageFailed, setQrImageFailed] = useState(false);
  const [exposure, setExposure] = useState(1.0);
  const [isRotating, setIsRotating] = useState(autoRotate);

  const modelViewerRef = useRef(null);

  // Memoized props and attributes passed to <model-viewer> to prevent re-scheduling updates
  const memoizedSrc = useMemo(() => {
    return src || (isCustomActive && customSrc ? customSrc : selectedModel.src);
  }, [src, isCustomActive, customSrc, selectedModel.src]);

  const memoizedIosSrc = useMemo(() => {
    return iosSrc || (isCustomActive ? '' : selectedModel.iosSrc);
  }, [iosSrc, isCustomActive, selectedModel.iosSrc]);

  const memoizedPoster = useMemo(() => {
    return poster || (!isCustomActive ? selectedModel.poster : '') || '';
  }, [poster, isCustomActive, selectedModel.poster]);

  const memoizedAlt = useMemo(() => {
    return alt || selectedModel.alt || 'NASA 3D Space Model';
  }, [alt, selectedModel.alt]);

  const memoizedExposure = useMemo(() => {
    return exposure.toFixed(2);
  }, [exposure]);

  const memoizedCameraOrbit = useMemo(() => {
    return cameraOrbit || (!isCustomActive ? selectedModel.cameraOrbit : null) || STATIC_CONFIG.defaultCameraOrbit;
  }, [cameraOrbit, isCustomActive, selectedModel.cameraOrbit]);

  const memoizedArModes = useMemo(() => {
    return arModes || STATIC_CONFIG.arModes;
  }, [arModes]);

  // Stable error handler callback
  const handleModelError = useCallback(() => {
    console.warn('[model-viewer] Failed to load GLB model:', memoizedSrc);
    setHasModelError(true);
  }, [memoizedSrc]);

  // 1. Implement SSR-safe dynamic loading for `@google/model-viewer` Web Component inside useEffect
  useEffect(() => {
    let isMounted = true;

    if (typeof window !== 'undefined') {
      // Quiet Lit dev mode warning flags before custom element definitions load
      window.litDisableDevMode = true;
      if (typeof globalThis !== 'undefined') {
        globalThis.litDisableDevMode = true;
      }

      // Check native WebXR support
      if (navigator && 'xr' in navigator && navigator.xr && typeof navigator.xr.isSessionSupported === 'function') {
        navigator.xr.isSessionSupported('immersive-ar')
          .then((supported) => {
            if (isMounted) setIsArSupported(Boolean(supported));
          })
          .catch(() => {
            if (isMounted) setIsArSupported(/iPhone|iPad|iPod|Android/i.test(navigator.userAgent));
          });
      } else if (typeof navigator !== 'undefined' && /iPhone|iPad|iPod|Android/i.test(navigator.userAgent)) {
        setIsArSupported(true);
      }

      // Check if already registered
      if (window.customElements && window.customElements.get('model-viewer')) {
        setIsScriptLoaded(true);
        return;
      }

      // The web component is bundled by Vite from the npm dependency, so the app
      // stays fully self-contained (no third-party CDN, works offline/PWA). If
      // the chunk genuinely fails to load, surface an honest error state rather
      // than injecting an external script or rendering an unresolved element.
      import('@google/model-viewer')
        .then(() => {
          if (isMounted) setIsScriptLoaded(true);
        })
        .catch((err) => {
          console.warn('[ArModelViewer] model-viewer chunk failed to load:', err);
          if (isMounted) setViewerLoadError(true);
        });
    }

    return () => {
      isMounted = false;
    };
  }, []);

  // Reset errors when model source changes
  useEffect(() => {
    setHasModelError(false);
  }, [memoizedSrc]);

  // Direct AR activation trigger
  const handleTriggerAR = useCallback(async () => {
    const isMobile = typeof navigator !== 'undefined' && /iPhone|iPad|iPod|Android/i.test(navigator.userAgent);
    if (!isMobile) {
      if (typeof navigator !== 'undefined' && 'xr' in navigator && navigator.xr && typeof navigator.xr.isSessionSupported === 'function') {
        const supported = await navigator.xr.isSessionSupported('immersive-ar').catch(() => false);
        if (!supported) {
          setShowQrModal(true);
          return;
        }
      } else {
        setShowQrModal(true);
        return;
      }
    }

    if (modelViewerRef.current && typeof modelViewerRef.current.activateAR === 'function') {
      try {
        await modelViewerRef.current.activateAR();
      } catch (err) {
        console.warn('Direct AR activation fallback:', err);
        setShowQrModal(true);
      }
    } else {
      setShowQrModal(true);
    }
  }, []);

  const handleSelectCatalogModel = useCallback((model) => {
    setIsCustomActive(false);
    setSelectedModel(model);
    if (onModelSelect) onModelSelect(model);
  }, [onModelSelect]);

  const handleApplyCustomUrl = useCallback((e) => {
    e.preventDefault();
    if (customSrc.trim()) {
      setIsCustomActive(true);
    }
  }, [customSrc]);

  const handleResetToDefault = useCallback(() => {
    setIsCustomActive(false);
    setSelectedModel(DEFAULT_AR_MODELS[0]);
    setHasModelError(false);
  }, []);

  // Re-attempt loading the bundled web-component chunk after a chunk failure
  // (e.g. a transient network error or a stale deployment hash).
  const handleRetryViewer = useCallback(() => {
    setViewerLoadError(false);
    setIsScriptLoaded(false);
    if (typeof window !== 'undefined' && window.customElements && window.customElements.get('model-viewer')) {
      setIsScriptLoaded(true);
      return;
    }
    import('@google/model-viewer')
      .then(() => setIsScriptLoaded(true))
      .catch((err) => {
        console.warn('[ArModelViewer] model-viewer retry failed:', err);
        setViewerLoadError(true);
      });
  }, []);

  const handleResetCamera = useCallback(() => {
    if (modelViewerRef.current) {
      modelViewerRef.current.cameraOrbit = STATIC_CONFIG.defaultCameraOrbit;
    }
  }, []);

  const getModelTitle = useCallback((m) => {
    if (lang === 'si') return m.nameSi || m.name;
    if (lang === 'ta') return m.nameTa || m.name;
    return m.name;
  }, [lang]);

  // Build clean mobile URL for QR Code projection
  const mobileArUrl = typeof window !== 'undefined' ? window.location.href : '';

  return (
    <div className={`w-full bg-surface/65 border border-line rounded-3xl p-4 sm:p-6 shadow-2xl space-y-5 font-sans text-ink backdrop-blur-xl relative overflow-hidden ${className}`}>
      {/* Background Ambient Glows */}
      <div className="absolute -top-32 -right-32 w-72 h-72 bg-cyan-600/10 rounded-full blur-3xl pointer-events-none" />
      <div className="absolute -bottom-32 -left-32 w-72 h-72 bg-purple-600/10 rounded-full blur-3xl pointer-events-none" />

      {/* Top Header Bar */}
      <div className="relative z-10 flex items-center justify-between gap-3 flex-wrap border-b border-line pb-4">
        <div className="flex items-center gap-3">
          <div className="relative w-11 h-11 rounded-[14px] bg-gradient-to-tr from-cyan-500 via-blue-600 to-indigo-600 p-0.5 flex items-center justify-center shadow-lg shadow-cyan-900/40 shrink-0">
            <div className="w-full h-full bg-abyss rounded-[14px] flex items-center justify-center">
              <Glasses className="w-5 h-5 text-cyan-400" />
            </div>
            <span className="absolute -top-1 -right-1 w-3 h-3 bg-emerald-400 rounded-full border-2 border-slate-950 animate-pulse" />
          </div>

          <div>
            <div className="flex items-center gap-2 flex-wrap">
              <h3 className="font-display font-bold text-base sm:text-lg text-white tracking-wide">
                {lang === 'si' ? 'WebXR අතථ්‍ය අභ්‍යවකාශ AR නරඹනය' :
                 lang === 'ta' ? 'WebXR ஆக்மென்டட் ரியாலிட்டி (AR) பார்வையாளர்' :
                 'WebXR Augmented Reality (AR) Space Viewer'}
              </h3>
              <span className="px-2.5 py-0.5 rounded-full text-[10px] font-mono font-bold bg-cyan-500/15 border border-cyan-500/30 text-cyan-300 flex items-center gap-1.5 shadow-sm">
                <Sparkles className="w-3 h-3 text-cyan-400" />
                @google/model-viewer
              </span>
              <span className="px-2 py-0.5 rounded-full text-[10px] font-mono bg-purple-500/15 border border-purple-500/30 text-derived">
                GLTF / GLB • Real Scale
              </span>
            </div>
            <p className="text-xs text-ink-3 font-mono mt-0.5">
              {lang === 'si' ? 'කැමරාව මඟින් ත්‍රිමාණ අභ්‍යවකාශ යානා සහ ගගනගාමීන් සැබෑ ලෝකයට ප්‍රක්ෂේපණය කරන්න' :
               lang === 'ta' ? 'உங்கள் கேமரா மூலம் 3D விண்கலங்கள் மற்றும் விண்வெளி வீரர்களை உண்மையான இடத்தில் நிறுவுங்கள்' :
               'Project photorealistic 3D NASA hardware into real-world physical space via WebXR & Scene Viewer'}
            </p>
          </div>
        </div>

        {/* Action Controls */}
        <div className="flex items-center gap-2">
          {/* Desktop QR Projector Trigger */}
          <button
            type="button"
            onClick={() => setShowQrModal(prev => !prev)}
            className="px-3 py-2 rounded-[10px] bg-surface-2/70 border border-line hover:border-cyan-400/60 text-ink-2 hover:text-ink font-mono text-xs flex items-center gap-1.5 transition cursor-pointer shadow-sm"
            title="Scan QR Code to project on Phone/Tablet"
          >
            <QrCode className="w-4 h-4 text-cyan-400" />
            <span className="hidden sm:inline">Phone AR QR</span>
          </button>

          {/* Elevated Header AR Button */}
          <button
            type="button"
            onClick={handleTriggerAR}
            className="px-4 py-2.5 rounded-[10px] bg-gradient-to-r from-cyan-500 via-blue-600 to-indigo-600 hover:from-cyan-400 hover:to-indigo-500 text-white font-mono text-xs font-bold transition shadow-lg shadow-cyan-900/40 flex items-center gap-2 cursor-pointer active:scale-95 transform"
            title="Launch Augmented Reality camera mode"
          >
            <Smartphone className="w-4 h-4 text-cyan-200" />
            <span>{lang === 'si' ? 'AR කැමරාව ආරම්භ කරන්න' : lang === 'ta' ? 'AR கேமராவைத் தொடங்கு' : 'Launch AR Camera'}</span>
          </button>
        </div>
      </div>

      {/* Model Selection Tabs & Custom GLB Input */}
      <div className="relative z-10 space-y-3">
        <div className="flex items-center justify-between gap-2 flex-wrap">
          <div className="flex items-center gap-2 overflow-x-auto pb-1 select-none scrollbar-none flex-1">
            <span className="text-[10px] font-mono text-ink-3 uppercase tracking-wider shrink-0 flex items-center gap-1 pl-1">
              <Box className="w-3 h-3 text-cyan-400" />
              {lang === 'si' ? 'ආකෘති:' : lang === 'ta' ? 'மாதிரிகள்:' : 'Models:'}
            </span>

            {DEFAULT_AR_MODELS.map((m) => {
              const isSelected = !isCustomActive && selectedModel.id === m.id;
              return (
                <button
                  key={m.id}
                  type="button"
                  onClick={() => handleSelectCatalogModel(m)}
                  className={`px-3 py-1.5 rounded-[10px] border text-xs font-mono transition whitespace-nowrap cursor-pointer flex items-center gap-1.5 shadow-sm ${
                    isSelected
                      ? 'bg-cyan-500/20 border-cyan-400 text-cyan-200 font-bold'
                      : 'bg-surface-2/70 border-line text-ink-2 hover:text-ink hover:border-line-strong'
                  }`}
                >
                  <span>{getModelTitle(m)}</span>
                  {isSelected && <Check className="w-3.5 h-3.5 text-cyan-400" />}
                </button>
              );
            })}
          </div>
        </div>

        {/* Custom URL Input Bar */}
        <form onSubmit={handleApplyCustomUrl} className="flex items-center gap-2 w-full text-xs font-mono">
          <div className="relative flex-1">
            <input
              type="url"
              value={customSrc}
              onChange={(e) => setCustomSrc(e.target.value)}
              placeholder="Paste any custom .glb or .gltf URL to project in AR (e.g. https://.../model.glb)"
              className="w-full pl-3.5 pr-3 py-2 rounded-[10px] bg-abyss/70 border border-line focus:border-cyan-400 text-white placeholder-slate-500 text-xs font-mono focus:outline-none transition shadow-inner"
            />
          </div>
          <button
            type="submit"
            disabled={!customSrc.trim()}
            className="px-3.5 py-2 rounded-[10px] bg-surface-2 border border-line hover:border-cyan-400 text-cyan-300 font-bold disabled:opacity-40 transition cursor-pointer disabled:cursor-not-allowed shrink-0"
          >
            Load Custom GLB
          </button>
        </form>
      </div>

      {/* 3D WebGL / WebXR Viewport */}
      <div className="relative w-full h-[380px] sm:h-[480px] rounded-[14px] overflow-hidden border border-line/90 bg-gradient-to-b from-[#020617] via-[#070e28] to-[#020617] select-none shadow-2xl flex items-center justify-center">
        {viewerLoadError ? (
          /* Web component chunk could not be loaded — honest recovery state. */
          <div className="p-6 text-center space-y-3 max-w-md">
            <div className="w-12 h-12 rounded-[14px] bg-rose-500/10 border border-rose-500/30 text-critical flex items-center justify-center mx-auto">
              <AlertCircle className="w-6 h-6" />
            </div>
            <h4 className="font-display font-bold text-sm text-white">
              {lang === 'si' ? '3D දර්ශකය පූරණය කළ නොහැක' : lang === 'ta' ? '3D பார்வையாளரை ஏற்ற முடியவில்லை' : 'Unable to load the 3D viewer'}
            </h4>
            <p className="text-xs text-ink-3 font-mono">
              {lang === 'si'
                ? 'දර්ශක කේත ඛණ්ඩය පූරණය වීමට අසමත් විය. ජාල සම්බන්ධතාවය පරීක්ෂා කර නැවත උත්සාහ කරන්න.'
                : lang === 'ta'
                  ? 'பார்வையாளர் குறியீட்டுப் பகுதி ஏற்றப்படவில்லை. இணைப்பைச் சரிபார்த்து மீண்டும் முயற்சிக்கவும்.'
                  : 'The viewer code chunk failed to load. Check your connection and try again.'}
            </p>
            <button
              type="button"
              onClick={handleRetryViewer}
              className="px-4 py-2 rounded-[10px] bg-cyan-600 hover:bg-cyan-500 text-white font-mono text-xs font-bold transition shadow-lg cursor-pointer inline-flex items-center gap-1.5"
            >
              <RefreshCw className="w-3.5 h-3.5" />
              {lang === 'si' ? 'නැවත උත්සාහ කරන්න' : lang === 'ta' ? 'மீண்டும் முயற்சிக்கவும்' : 'Retry'}
            </button>
          </div>
        ) : !isScriptLoaded ? (
          /* Registration in progress — never an unresolved blank element. */
          <div className="flex flex-col items-center gap-3 text-center p-6" role="status" aria-live="polite">
            <span className="h-9 w-9 animate-spin rounded-full border-2 border-cyan-500/25 border-t-cyan-400" />
            <p className="text-xs font-mono text-ink-3">
              {lang === 'si' ? '3D දර්ශකය පූරණය වෙමින්…' : lang === 'ta' ? '3D பார்வையாளர் ஏற்றப்படுகிறது…' : 'Loading 3D viewer…'}
            </p>
          </div>
        ) : hasModelError ? (
          /* Model asset error fallback view */
          <div className="p-6 text-center space-y-3 max-w-md">
            <div className="w-12 h-12 rounded-[14px] bg-rose-500/10 border border-rose-500/30 text-critical flex items-center justify-center mx-auto">
              <AlertCircle className="w-6 h-6" />
            </div>
            <h4 className="font-display font-bold text-sm text-white">
              {lang === 'si' ? '3D ආකෘතිය පූරණය කළ නොහැක' : lang === 'ta' ? '3D மாதிரியை ஏற்ற முடியவில்லை' : 'Unable to load 3D model'}
            </h4>
            <p className="text-xs text-ink-3 font-mono">
              {lang === 'si'
                ? 'තෝරාගත් ආකෘතිය පූරණය වීමට අසමත් විය. ලැයිස්තුවේ පළමු අභ්‍යවකාශ යානා ආකෘතිය වෙත ආපසු යන්න.'
                : lang === 'ta'
                  ? 'தேர்ந்தெடுக்கப்பட்ட மாதிரியை ஏற்ற முடியவில்லை. பட்டியலில் முதல் விண்கல மாதிரிக்கு மீட்டமைக்கவும்.'
                  : 'The selected model could not be loaded. Reset to the first spacecraft in the catalog and try again.'}
            </p>
            <button
              type="button"
              onClick={handleResetToDefault}
              className="px-4 py-2 rounded-[10px] bg-cyan-600 hover:bg-cyan-500 text-white font-mono text-xs font-bold transition shadow-lg cursor-pointer"
            >
              {lang === 'si' ? 'පළමු ආකෘතියට මාරුවන්න' : lang === 'ta' ? 'முதல் மாதிரிக்கு மீட்டமை' : 'Reset to first model'}
            </button>
          </div>
        ) : (
          /* Memoized Stable <model-viewer> canvas */
          <StableModelViewerCanvas
            viewerRef={modelViewerRef}
            src={memoizedSrc}
            iosSrc={memoizedIosSrc}
            poster={memoizedPoster}
            alt={memoizedAlt}
            ar={ar}
            arModes={memoizedArModes}
            cameraControls={cameraControls}
            cameraOrbit={memoizedCameraOrbit}
            autoRotate={isRotating}
            exposure={memoizedExposure}
            onError={handleModelError}
          />
        )}

        {/* Viewport Floating Controls */}
        <div className="absolute top-4 left-4 z-10 flex items-center gap-2 flex-wrap pointer-events-none">
          <span
            className={`px-2.5 py-1 rounded-[10px] bg-abyss/70 border border-line text-[10px] font-mono backdrop-blur-md flex items-center gap-1.5 shadow-md ${
              isArSupported ? 'text-cyan-300' : 'text-ink-3'
            }`}
          >
            <span
              className={`w-2 h-2 rounded-full ${
                isArSupported ? 'bg-emerald-400 animate-ping' : 'bg-ink-4'
              }`}
            />
            {isArSupported
              ? lang === 'si'
                ? 'WEBXR සූදානම්'
                : lang === 'ta'
                  ? 'WEBXR தயார்'
                  : 'WEBXR READY'
              : lang === 'si'
                ? '3D දර්ශකය'
                : lang === 'ta'
                  ? '3D பார்வையாளர்'
                  : '3D VIEWER'}
          </span>
          <span className="px-2.5 py-1 rounded-[10px] bg-abyss/70 border border-line text-[10px] font-mono text-ink-2 backdrop-blur-md">
            DRAG TO ORBIT • PINCH TO ZOOM
          </span>
        </div>

        {/* Quick Toolbar on Bottom Left */}
        <div className="absolute bottom-4 left-4 z-10 flex items-center gap-1.5 bg-abyss/70 border border-line rounded-[10px] p-1 backdrop-blur-md">
          {/* Auto-Rotate Toggle */}
          <button
            type="button"
            onClick={() => setIsRotating(prev => !prev)}
            className={`p-1.5 rounded-[8px] border text-xs font-mono transition cursor-pointer ${
              isRotating 
                ? 'bg-cyan-500/20 border-cyan-400 text-cyan-300' 
                : 'bg-surface/60 border-line text-ink-3 hover:text-ink'
            }`}
            title="Toggle Auto-Rotation"
          >
            <RotateCw className="w-3.5 h-3.5" />
          </button>

          {/* Reset Camera */}
          <button
            type="button"
            onClick={handleResetCamera}
            className="p-1.5 rounded-[8px] bg-surface/60 border border-line text-ink-3 hover:text-ink text-xs font-mono transition cursor-pointer"
            title="Reset Camera View"
          >
            <RefreshCw className="w-3.5 h-3.5" />
          </button>

          {/* Exposure Preset Switch */}
          <button
            type="button"
            onClick={() => setExposure(prev => prev >= 1.5 ? 0.75 : prev + 0.25)}
            className="p-1.5 rounded-[8px] bg-surface/60 border border-line text-ink-3 hover:text-ink text-xs font-mono transition cursor-pointer flex items-center gap-1"
            title="Adjust Lighting Exposure"
          >
            <Sun className="w-3.5 h-3.5 text-caution" />
            <span className="text-[10px] font-mono">{exposure.toFixed(1)}x</span>
          </button>
        </div>
      </div>

      {/* Model Telemetry & Engineering Specs */}
      <div className="relative z-10 p-4 rounded-[14px] bg-abyss/60 border border-line flex items-center justify-between gap-4 flex-wrap">
        <div className="space-y-1">
          <div className="flex items-center gap-2">
            <span className="text-[10px] font-mono text-cyan-400 uppercase tracking-wider font-bold">
              {isCustomActive ? 'Custom User Asset' : selectedModel.category}
            </span>
            <span className="text-ink-4">•</span>
            <span className="text-[10px] font-mono text-signal">
              {memoizedArModes}
            </span>
          </div>

          <h4 className="text-sm font-bold text-white font-display">
            {isCustomActive ? 'Custom GLTF 3D Exploration Asset' : getModelTitle(selectedModel)}
          </h4>
          <p className="text-xs text-ink-3 font-sans max-w-2xl leading-relaxed">
            {isCustomActive ? `Rendering custom 3D model asset from: ${customSrc}` : selectedModel.desc}
          </p>
        </div>

        <div className="flex items-center gap-3 text-xs font-mono text-ink-3 shrink-0">
          <div className="text-right">
            <span className="text-[10px] text-ink-4 block uppercase">AR Standard</span>
            <span className="text-cyan-300 font-bold">WebXR / Quick-Look</span>
          </div>
        </div>
      </div>

      {/* Desktop QR Modal for Instant Mobile Phone Testing */}
      {showQrModal && (
        <div className="fixed inset-0 z-50 bg-black/80 backdrop-blur-md flex items-center justify-center p-4">
          <div className="bg-surface/60 border border-cyan-500/40 rounded-3xl p-6 max-w-md w-full space-y-4 shadow-2xl relative text-center">
            <button
              type="button"
              onClick={() => setShowQrModal(false)}
              className="absolute top-4 right-4 text-ink-3 hover:text-ink font-mono text-sm cursor-pointer"
            >
              ✕
            </button>

            <div className="w-12 h-12 rounded-[14px] bg-cyan-500/20 border border-cyan-400/40 text-cyan-300 flex items-center justify-center mx-auto shadow-lg shadow-cyan-950/50">
              <Camera className="w-6 h-6" />
            </div>

            <div className="space-y-1">
              <h3 className="font-display font-bold text-lg text-white">
                Scan with Smartphone Camera
              </h3>
              <p className="text-xs text-ink-3 font-mono">
                Point your iPhone (iOS Quick Look) or Android (Scene Viewer / WebXR) camera at this QR code to view the 3D model in your physical room:
              </p>
            </div>

            {/* Generated QR Code Container, with an offline-safe fallback if
                the external image host is unreachable. */}
            {qrImageFailed ? (
              <div className="p-4 bg-white rounded-[14px] inline-block shadow-2xl mx-auto w-52">
                <p className="text-[11px] font-mono text-slate-700 break-all leading-relaxed">
                  {mobileArUrl}
                </p>
                <p className="mt-2 text-[10px] font-mono text-slate-500">
                  Open this address on your phone to launch the AR viewer.
                </p>
              </div>
            ) : (
              <div className="p-4 bg-white rounded-[14px] inline-block shadow-2xl mx-auto">
                <img
                  src={`https://api.qrserver.com/v1/create-qr-code/?size=200x200&data=${encodeURIComponent(mobileArUrl)}`}
                  alt="Mobile AR Projector QR Code"
                  className="w-48 h-48 block"
                  onError={() => setQrImageFailed(true)}
                />
              </div>
            )}

            <p className="text-[11px] font-mono text-cyan-300">
              No app download required • Uses native browser WebXR
            </p>
          </div>
        </div>
      )}
    </div>
  );
}

export default memo(ArModelViewer);
