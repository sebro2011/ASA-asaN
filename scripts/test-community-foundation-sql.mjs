import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

const alice='11111111-1111-4111-8111-111111111111';
const bob='22222222-2222-4222-8222-222222222222';
const mod='33333333-3333-4333-8333-333333333333';
const sql=await readFile(new URL('../supabase/migrations/20261123000000_community_foundation.sql',import.meta.url),'utf8');

test('community SQL enforces moderation, ownership, suspension and private reports', async () => {
  const db=new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth; create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
      grant usage on schema auth, public to anon, authenticated; grant execute on function auth.uid() to anon, authenticated;`);
    await db.exec(sql);
    await db.query('insert into auth.users(id) values($1),($2),($3)',[alice,bob,mod]);
    await db.query('insert into public.community_moderators(user_id) values($1)',[mod]);
    const role=async (id) => {await db.exec('reset role; set role authenticated'); await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);};
    await role(alice);
    await db.query("insert into public.community_profiles(display_name) values('Stargazer')");
    const post=(await db.query("insert into public.community_posts(body) values('First observations') returning id,status")).rows[0];
    assert.equal(post.status,'pending');
    await assert.rejects(db.query("insert into public.community_posts(body,status) values('bad','approved')"),/permission denied/i);
    await assert.rejects(db.query('select * from public.community_moderators'),/permission denied/i);
    await role(bob);
    assert.equal((await db.query('select * from public.community_posts')).rows.length,0);
    assert.equal((await db.query('select * from public.community_profiles')).rows.length,0);
    await assert.rejects(db.query("update public.community_profiles set display_name='Impersonator' where user_id=$1 returning user_id",[alice]).then(r=>{if (!r.rows.length) throw Error('ownership denied');}),/ownership denied/);
    await assert.rejects(db.query('select * from public.community_report_queue()'),/not authorized/i);
    await assert.rejects(db.query('select * from public.community_review_queue()'),/not authorized/i);
    await assert.rejects(db.query('insert into public.community_comments(post_id,body) values($1,$2)',[post.id,'hello']),/row-level security/i);
    await role(mod);
    assert.equal((await db.query('select * from public.community_review_queue()')).rows.length,2);
    assert.equal((await db.query("select public.community_review($1,'profile','approved','Stargazer') as ok",[alice])).rows[0].ok,true);
    assert.equal((await db.query("select public.community_review($1,'post','approved','stale text') as ok",[post.id])).rows[0].ok,false);
    await assert.rejects(db.query('select * from public.community_audit_log'),/permission denied/i);
    assert.equal((await db.query("select public.community_review($1,'post','approved','First observations') as ok",[post.id])).rows[0].ok,true);
    await db.exec("reset role; set role anon; select set_config('request.jwt.claim.sub','',false)");
    assert.equal((await db.query('select * from public.community_posts')).rows.length,1);
    assert.equal((await db.query('select display_name from public.community_profiles')).rows[0].display_name,'Stargazer');
    await assert.rejects(db.query("insert into public.community_posts(body) values('anon')"),/permission denied/i);
    await assert.rejects(db.query('select * from public.community_notifications'),/permission denied/i);
    await role(alice);
    const notifications=(await db.query('select * from public.community_notifications order by event')).rows;
    assert.deepEqual(notifications.map(n=>n.event),['post_approved','profile_approved']);
    await assert.rejects(db.query("insert into public.community_notifications(recipient_id,event) values($1,'post_approved')",[bob]),/permission denied/i);
    await role(bob);
    assert.equal((await db.query('select * from public.community_notifications')).rows.length,0);
    assert.equal((await db.query('update public.community_notifications set read_at=now() where id=$1 returning id',[notifications[0].id])).rows.length,0);
    assert.equal((await db.query('delete from public.community_notifications where id=$1 returning id',[notifications[0].id])).rows.length,0);
    await role(alice);
    assert.equal((await db.query('update public.community_notifications set read_at=now() where id=$1 returning id',[notifications[0].id])).rows.length,1);
    await assert.rejects(db.query("update public.community_notifications set event='post_rejected' where id=$1",[notifications[0].id]),/permission denied/i);
    await role(bob);
    const comment=(await db.query('insert into public.community_comments(post_id,body) values($1,$2) returning id,status',[post.id,'Hello Mars'])).rows[0];
    assert.equal(comment.status,'pending');
    await db.query('insert into public.community_likes(post_id) values($1)',[post.id]);
    await db.query('insert into public.community_reports(post_id,reason) values($1,$2)',[post.id,'Needs review']);
    await assert.rejects(db.query("select public.community_resolve_report($1,'removed')",[post.id]),/not authorized/i);
    await assert.rejects(db.query('select * from public.community_reports'),/permission denied/i);
    await role(alice);
    assert.equal((await db.query('select * from public.community_likes')).rows.length,0);
    assert.equal((await db.query('select * from public.community_comments')).rows.length,0);
    assert.equal((await db.query('delete from public.community_posts where author_id=$1 returning id',[bob])).rows.length,0);
    await db.query("update public.community_posts set body='Updated text' where id=$1",[post.id]);
    await db.query("update public.community_profiles set display_name='New name' where user_id=$1",[alice]);
    await role(mod);
    const report=(await db.query('select * from public.community_report_queue()')).rows[0];
    assert.equal(report.reported_body,'First observations');
    assert.equal((await db.query("select public.community_resolve_report($1,'removed') as result",[report.id])).rows[0].result,'stale');
    assert.equal((await db.query('select * from public.community_report_queue()')).rows.length,0);
    assert.equal((await db.query("select public.community_review($1,'post','approved','Updated text') as ok",[post.id])).rows[0].ok,true);
    await role(bob);
    await db.query('insert into public.community_reports(post_id,reason) values($1,$2)',[post.id,'Still concerning']);
    await assert.rejects(db.query('insert into public.community_reports(post_id,reason) values($1,$2)',[post.id,'Duplicate report']),/unique/i);
    await role(mod);
    const second=(await db.query('select * from public.community_report_queue()')).rows[0];
    assert.equal((await db.query("select public.community_resolve_report($1,'removed') as result",[second.id])).rows[0].result,'removed');
    assert.equal((await db.query("select public.community_resolve_report($1,'removed') as result",[second.id])).rows[0].result,'missing');
    await role(bob);
    assert.equal((await db.query("select * from public.community_notifications where event='report_resolved'")).rows.length,2);
    assert.equal((await db.query("select * from public.community_notifications where event='post_rejected'")).rows.length,0);
    await db.exec("reset role; set role anon; select set_config('request.jwt.claim.sub','',false)");
    assert.equal((await db.query('select * from public.community_posts')).rows.length,0,'edits return to review');
    assert.equal((await db.query('select * from public.community_profiles')).rows.length,0,'name edits return to review');
    await db.exec('reset role');
    await db.query("insert into public.community_suspensions(user_id,until_at,reason) values($1,now()+interval '1 hour','safety')",[bob]);
    await role(bob);
    await assert.rejects(db.query("insert into public.community_posts(body) values('suspended')"),/community write unavailable|row-level security/i);
    await role(alice);
    for(let i=0;i<3;i++) await db.query('insert into public.community_posts(body) values($1)',[`post ${i}`]);
    await assert.rejects(db.query("insert into public.community_posts(body) values('over quota')"),/rate limit/i);
  } finally { await db.close(); }
});

test('science groups enforce moderation, private membership and member-only posting', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated;
      create schema auth; create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      grant usage on schema auth, public to anon, authenticated; grant execute on function auth.uid() to anon, authenticated;`);
    await db.exec(sql);
    await db.query('insert into auth.users(id) values($1),($2),($3)',[alice,bob,mod]);
    await db.query('insert into public.community_moderators(user_id) values($1)',[mod]);
    const role=async id => { await db.exec('reset role; set role authenticated'); await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]); };
    await role(alice);
    const group=(await db.query("insert into public.community_groups(name,description,category) values('Mars club','Explore Mars safely','mars') returning id,status")).rows[0];
    assert.equal(group.status,'pending');
    assert.equal((await db.query('select role from public.community_group_members')).rows[0].role,'owner');
    assert.equal((await db.query('delete from public.community_group_members returning group_id')).rows.length,0,'owner cannot leave and orphan a group');
    await assert.rejects(db.query("insert into public.community_groups(name,description,category) values('False category','Description','invalid')"),/check constraint/i);
    await role(bob);
    assert.equal((await db.query('select * from public.community_groups')).rows.length,0);
    await assert.rejects(db.query('insert into public.community_group_members(group_id) values($1)',[group.id]),/row-level security/i);
    await assert.rejects(db.query("insert into public.community_posts(group_id,body) values($1,'unauthorized')",[group.id]),/row-level security/i);
    await assert.rejects(db.query("insert into public.community_group_members(group_id,role) values($1,'owner')",[group.id]),/permission denied/i);
    await role(mod);
    assert.equal((await db.query('select kind from public.community_review_queue()')).rows[0].kind,'group');
    assert.equal((await db.query("select public.community_review($1,'group','approved',$2) as ok",[group.id,'Mars club\nExplore Mars safely'])).rows[0].ok,true);
    await db.exec("reset role; set role anon; select set_config('request.jwt.claim.sub','',false)");
    assert.equal((await db.query('select * from public.community_groups')).rows.length,1);
    await assert.rejects(db.query('select * from public.community_group_members'),/permission denied/i);
    await role(bob);
    await assert.rejects(db.query("insert into public.community_posts(group_id,body) values($1,'non member')",[group.id]),/row-level security/i);
    await db.query('insert into public.community_group_members(group_id) values($1)',[group.id]);
    assert.equal((await db.query('select * from public.community_group_members')).rows.length,1,'cannot view owner membership');
    await assert.rejects(db.query('select * from public.community_group_roster($1)',[group.id]),/not authorized/i);
    await assert.rejects(db.query("update public.community_group_members set role='owner' where group_id=$1",[group.id]),/permission denied/i);
    await role(alice);
    assert.equal((await db.query('select * from public.community_group_roster($1)',[group.id])).rows.length,2);
    assert.equal((await db.query("select public.community_group_manage($1,$2,'promote') as ok",[group.id,bob])).rows[0].ok,true);
    await assert.rejects(db.query("select public.community_group_manage($1,$2,'remove')",[group.id,alice]),/not authorized/i);
    await role(mod);
    await db.query('insert into public.community_group_members(group_id) values($1)',[group.id]);
    await role(bob);
    assert.equal((await db.query('select * from public.community_group_roster($1)',[group.id])).rows.length,3);
    await assert.rejects(db.query("select public.community_group_manage($1,$2,'promote')",[group.id,mod]),/not authorized/i);
    await assert.rejects(db.query("select public.community_group_manage($1,$2,'remove')",[group.id,alice]),/not authorized/i);
    assert.equal((await db.query("select public.community_group_manage($1,$2,'remove') as ok",[group.id,mod])).rows[0].ok,true);
    await role(alice);
    assert.equal((await db.query("select public.community_group_manage($1,$2,'demote') as ok",[group.id,bob])).rows[0].ok,true);
    await role(bob);
    await assert.rejects(db.query('select * from public.community_group_roster($1)',[group.id]),/not authorized/i);
    const post=(await db.query("insert into public.community_posts(group_id,body) values($1,'Orbital observations') returning id,status",[group.id])).rows[0];
    assert.equal(post.status,'pending');
    await role(mod);
    assert.equal((await db.query("select public.community_review($1,'post','approved','Orbital observations') as ok",[post.id])).rows[0].ok,true);
    await role(bob);
    assert.equal((await db.query('delete from public.community_group_members where group_id=$1 returning group_id',[group.id])).rows.length,1);
    await assert.rejects(db.query("insert into public.community_posts(group_id,body) values($1,'left group')",[group.id]),/row-level security/i);
    await db.exec("reset role; set role anon; select set_config('request.jwt.claim.sub','',false)");
    assert.equal((await db.query('select * from public.community_posts')).rows.length,1);
  } finally { await db.close(); }
});
